#!/usr/bin/env python3
"""Refresh docs/published-tools.txt from a saved Loomi Connect `list_all_tools` response.

The tool list only comes from Loomi Connect itself, over the user's own MCP connection, so
it can't be fetched here or in CI. In a session with Loomi Connect connected, call
`list_all_tools`, save the JSON response to a file, then run:

    python3 scripts/update_published_tools.py <saved response.json>

Tools tagged `internal` are left out: skills never call them (see CHARTER.md).
Standard library only; no network access.
"""
import argparse
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "published-tools.txt"
HEADER = (
    "# Published Loomi Connect tools, from list_all_tools (tools tagged internal left out).\n"
    "# Generated by scripts/update_published_tools.py; refresh it after a live tool check.\n"
)


def fail(msg):
    print(msg, file=sys.stderr)
    sys.exit(1)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("response", help="saved list_all_tools JSON response")
    ap.add_argument("--today", help="date the list was checked, YYYY-MM-DD (default: today, UTC)")
    ap.add_argument("--out", default=str(OUT), help="file to write (default: docs/published-tools.txt)")
    a = ap.parse_args()
    try:
        data = json.loads(Path(a.response).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        fail(f"Can't read {a.response}: {e}")
    tools = data.get("tools") if isinstance(data, dict) else None
    if not isinstance(tools, list) or not tools:
        fail(f"{a.response} has no 'tools' list. Save the whole list_all_tools response.")
    today = a.today or dt.datetime.now(dt.timezone.utc).date().isoformat()
    try:
        dt.date.fromisoformat(today)
    except ValueError:
        fail(f"--today must be YYYY-MM-DD, got {today!r}")
    rows = []
    for t in tools:
        name, tags = t.get("name"), sorted(t.get("tags") or [])
        if not name or "internal" in tags:
            continue
        rows.append(f"{name}\t{','.join(tags)}")
    text = HEADER + f"# checked: {today}\n" + "\n".join(sorted(rows)) + "\n"
    try:
        Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    except OSError as e:
        fail(f"Can't write {a.out}: {e}")
    print(f"Wrote {len(rows)} tools (checked {today}) to {a.out}")


if __name__ == "__main__":
    main()
